const CSS_FILES = (function findCss(dir = "app", acc = []) {
  for (const name of readdirSync(join(ROOT_DIR, dir))) {
    const rel = `${dir}/${name}`
    if (statSync(join(ROOT_DIR, rel)).isDirectory()) findCss(rel, acc)
    else if (name.endsWith(".css")) acc.push(rel)
  }
  return acc.sort()
})()

